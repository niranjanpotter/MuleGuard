import * as path from 'path';
import * as vscode from 'vscode';

export async function explainDataWeaveFile(document?: vscode.TextDocument): Promise<void> {
  const targetDoc = document || vscode.window.activeTextEditor?.document;
  if (!targetDoc || (!targetDoc.fileName.endsWith('.dwl') && targetDoc.languageId !== 'dataweave')) {
    void vscode.window.showInformationMessage('MuleGuard: Please open a DataWeave (.dwl) file to generate a logic summary.');
    return;
  }

  const content = targetDoc.getText();
  const baseName = path.basename(targetDoc.fileName);

  // Extract header and body
  const parts = content.split('---');
  const header = parts.length > 1 ? parts[0] : '';
  const body = parts.length > 1 ? parts.slice(1).join('---') : parts[0];

  // Detect output format
  const outputMatch = /output\s+([a-zA-Z0-9_/]+)/i.exec(header);
  const outputFormat = outputMatch ? outputMatch[1] : 'application/json';

  // Detect input and variables
  const vars = (header.match(/var\s+([a-zA-Z0-9_]+)/g) || []).map(v => v.replace('var', '').trim());
  const functions = (header.match(/fun\s+([a-zA-Z0-9_]+)/g) || []).map(f => f.replace('fun', '').trim());

  // Analyze body operations
  const operations: string[] = [];
  if (/\bmap\b/.test(body)) operations.push('Transforms array elements using `map`');
  if (/\bfilter\b/.test(body)) operations.push('Filters records based on conditional logic using `filter`');
  if (/\breduce\b/.test(body)) operations.push('Aggregates data into a single value using `reduce`');
  if (/\bgroupBy\b/.test(body)) operations.push('Categorizes records into groups using `groupBy`');
  if (/\bdistinctBy\b/.test(body)) operations.push('Deduplicates elements using `distinctBy`');
  if (/\bif\b/.test(body)) operations.push('Executes conditional branching (`if/else`)');
  if (/\bdefault\b/.test(body)) operations.push('Includes null-safe fallback defaults (`default`)');

  let report = `# ⚡ MuleGuard DataWeave Architecture & Logic Summary\n\n`;
  report += `**File:** \`${baseName}\`  \n`;
  report += `**Target Output Format:** \`${outputFormat}\`  \n\n`;

  report += `## 1. Script Architecture & Declarations\n`;
  report += `- **Declared Variables:** ${vars.length > 0 ? vars.map(v => `\`${v}\``).join(', ') : 'None'}\n`;
  report += `- **Custom Helper Functions:** ${functions.length > 0 ? functions.map(f => `\`${f}()\``).join(', ') : 'None'}\n\n`;

  report += `## 2. Business Transformation Operations\n`;
  if (operations.length === 0) {
    report += `- Direct field-to-field object mapping.\n`;
  } else {
    for (const op of operations) {
      report += `- ${op}\n`;
    }
  }

  report += `\n## 3. Data Flow Overview\n`;
  report += `This transformation accepts inbound source data (via \`payload\` or \`vars\`), processes properties, and produces a structured \`${outputFormat}\` output payload ready for downstream consumption or API responses.\n\n`;

  report += `---\n*Generated by MuleGuard DataWeave Intelligence.*`;

  const doc = await vscode.workspace.openTextDocument({
    language: 'markdown',
    content: report
  });
  await vscode.window.showTextDocument(doc);
}
